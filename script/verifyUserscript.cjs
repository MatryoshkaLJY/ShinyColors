const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const { createHeader, scriptVersion, downloadURL, updateURL } = require('./userscript.cjs')

const script = readFileSync('dist/ShinyColors.user.js', 'utf8')
const meta = readFileSync('dist/ShinyColors.meta.js', 'utf8')
assert.equal(meta, `${createHeader()}\n`)
assert.ok(script.startsWith(meta.trimEnd()), 'Script and update metadata headers must match')
assert.ok(meta.includes(`// @downloadURL  ${downloadURL}`))
assert.ok(meta.includes(`// @updateURL    ${updateURL}`))
assert.ok(script.includes(downloadURL), 'The manual update menu must use the fork release')
assert.ok(!meta.includes('localhost'), 'Published metadata must not point to a local server')
assert.ok(readFileSync('dist/LICENSE-code.txt', 'utf8').includes('MIT License'))
assert.ok(readFileSync('dist/LICENSE-effects.txt', 'utf8').includes('NonCommercial'))
console.log(`Verified userscript release ${scriptVersion()}`)
